    FECHA_CUP_ASIGNADO  TIMESTAMP,
    ACTIVO              NUMBER(1)       DEFAULT 1 NOT NULL,
    MONTO_ESTIMADO_INVERSION NUMBER     NOT NULL,
    SECTOR              VARCHAR2(50)    NOT NULL,
    EJE_TEMATICO        VARCHAR2(50)    NOT NULL,
    ES_PROYECTO_EMERGENCIA NUMBER(1),
    TIPO_EVENTO         VARCHAR2(100),
    NUMERO_DECRETO_LEGISLATIVO VARCHAR2(50),
    EJE_PLAN_GOBIERNO   VARCHAR2(50),
    PLAN_SECTORIAL_REGIONAL VARCHAR2(50),
    DESCRIPCION_PROYECTO VARCHAR2(1000) NOT NULL,
    FECHA_CREACION      TIMESTAMP       DEFAULT SYSTIMESTAMP,
    FECHA_MODIFICACION  TIMESTAMP,
    USUARIO_CREACION    VARCHAR2(100),
    USUARIO_MODIFICACION VARCHAR2(100),
    CONSTRAINT PK_PROYECTO PRIMARY KEY (ID_PROYECTO),
    CONSTRAINT UK_PROYECTO_CUP UNIQUE (CUP),
    CONSTRAINT FK_PROYECTO_UE FOREIGN KEY (ID_UNIDAD_EJECUTORA) REFERENCES UNIDAD_EJECUTORA (ID_UNIDAD_EJECUTORA),
    CONSTRAINT FK_PROYECTO_INSTITUCION FOREIGN KEY (ID_INSTITUCION) REFERENCES INSTITUCION (ID_INSTITUCION),
    CONSTRAINT CK_PROYECTO_INICIATIVA CHECK (INICIATIVA_INVERSION IN ('PROGRAMA','PROYECTO','ESTUDIO_GENERAL')),
    CONSTRAINT CK_PROYECTO_ESTADO CHECK (ESTADO IN ('EN_REGISTRO','ENVIADO_DGICP_REGISTRO','OBSERVADO_DGICP_REGISTRO',
        'CUP_ASIGNADO','EN_FORMULACION','EN_VIABILIDAD','VIABLE','NO_VIABLE','ELEGIBLE','NO_ELEGIBLE',
