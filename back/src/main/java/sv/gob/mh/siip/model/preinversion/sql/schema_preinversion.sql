    INICIATIVA_INVERSION VARCHAR2(20)   NOT NULL,
    ID_UNIDAD_EJECUTORA NUMBER(19)      NOT NULL,
    ID_INSTITUCION      NUMBER(19)      NOT NULL,
    ESTADO              VARCHAR2(40)    NOT NULL,
