-- 3. MODIFICACIONES AL CONVENIO (CU-MPD-03)
--------------------------------------------------------------------------------

CREATE SEQUENCE AJUSTE_CONVENIO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE AJUSTE_CONVENIO (
    ID_AJUSTE_CONVENIO  NUMBER(19)      NOT NULL,
    ID_CONVENIO         NUMBER(19)      NOT NULL,
    TIPO_AJUSTE         VARCHAR2(20)    NOT NULL,
    DOCUMENTO_AUTORIZACION VARCHAR2(500),
    JUSTIFICACION        VARCHAR2(2000),
    FECHA_AJUSTE         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AJUSTE_CONVENIO PRIMARY KEY (ID_AJUSTE_CONVENIO),
    CONSTRAINT FK_AJUSTE_CONVENIO_CONV FOREIGN KEY (ID_CONVENIO) REFERENCES CONVENIO (ID_CONVENIO),
    CONSTRAINT CK_AJUSTE_CONVENIO_TIPO CHECK (TIPO_AJUSTE IN ('ADENDA','REESTRUCTURACION','NA'))
);
COMMENT ON TABLE AJUSTE_CONVENIO IS 'Ajuste (adenda/reestructuracion) sobre un convenio. CU-MPD-03';

CREATE SEQUENCE COMP_CONV_AJUSTE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE COMPONENTE_CONVENIO_AJUSTE (
    ID_COMPONENTE_AJUSTE NUMBER(19)     NOT NULL,
    ID_AJUSTE_CONVENIO  NUMBER(19)      NOT NULL,
    ID_COMPONENTE_CONVENIO NUMBER(19),
    NOMBRE_COMPONENTE    VARCHAR2(250)  NOT NULL,
    MONTO_ASIGNADO_INICIAL NUMBER(18,2) NOT NULL,
    MONTO_ASIGNADO_AJUSTADO NUMBER(18,2) NOT NULL,
    PORCENTAJE           NUMBER(5,2),
    CONSTRAINT PK_COMP_CONV_AJUSTE PRIMARY KEY (ID_COMPONENTE_AJUSTE),
    CONSTRAINT FK_COMP_CONV_AJUSTE FOREIGN KEY (ID_AJUSTE_CONVENIO) REFERENCES AJUSTE_CONVENIO (ID_AJUSTE_CONVENIO),
    CONSTRAINT FK_COMP_CONV_AJ_ORIGEN FOREIGN KEY (ID_COMPONENTE_CONVENIO) REFERENCES COMPONENTE_CONVENIO (ID_COMPONENTE_CONVENIO)
);
COMMENT ON TABLE COMPONENTE_CONVENIO_AJUSTE IS 'Distribucion ajustada (inicial vs ajustada) de un componente. CU-MPD-03. RN07: suma = monto convenio.';

CREATE SEQUENCE AMPLIACION_PLAZO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE AMPLIACION_PLAZO_CONVENIO (
    ID_AMPLIACION_PLAZO NUMBER(19)      NOT NULL,
    ID_CONVENIO         NUMBER(19)      NOT NULL,
    FECHA_AMPLIACION_DESEMBOLSO DATE    NOT NULL,
    PERIODO_AJUSTADO_CALCULADO VARCHAR2(100),
    DOCUMENTO_AUTORIZACION VARCHAR2(500),
    FECHA_REGISTRO        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AMPLIACION_PLAZO PRIMARY KEY (ID_AMPLIACION_PLAZO),
    CONSTRAINT FK_AMPLIACION_PLAZO_CONV FOREIGN KEY (ID_CONVENIO) REFERENCES CONVENIO (ID_CONVENIO)
);
COMMENT ON TABLE AMPLIACION_PLAZO_CONVENIO IS 'Ampliacion de plazo del ultimo desembolso del convenio. CU-MPD-03';

