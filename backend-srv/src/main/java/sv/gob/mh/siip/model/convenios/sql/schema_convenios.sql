-- 4. FICHA DEL CONVENIO — PROYECTOS ASOCIADOS (CU-MPD-04)
--------------------------------------------------------------------------------

CREATE SEQUENCE PROYECTO_CONVENIO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE PROYECTO_CONVENIO (
    ID_PROYECTO_CONVENIO NUMBER(19)     NOT NULL,
    ID_CONVENIO         NUMBER(19)      NOT NULL,
    ID_PROYECTO         NUMBER(19)      NOT NULL,
    MONTO_COMPROMETIDO   NUMBER(18,2)   DEFAULT 0 NOT NULL,
    ES_PROGRAMA_PRINCIPAL NUMBER(1)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PROYECTO_CONVENIO PRIMARY KEY (ID_PROYECTO_CONVENIO),
    CONSTRAINT UK_PROYECTO_CONVENIO UNIQUE (ID_CONVENIO, ID_PROYECTO),
    CONSTRAINT FK_PROY_CONV_CONVENIO FOREIGN KEY (ID_CONVENIO) REFERENCES CONVENIO (ID_CONVENIO),
    CONSTRAINT FK_PROY_CONV_PROYECTO FOREIGN KEY (ID_PROYECTO) REFERENCES PROYECTO (ID_PROYECTO)
);
COMMENT ON TABLE PROYECTO_CONVENIO IS 'Proyecto vinculado al convenio, con monto comprometido y bandera de Programa Principal. CU-MPD-04';

